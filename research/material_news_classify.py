_COMPILED: dict[str, re.Pattern] = {
    cat: re.compile("|".join(re.escape(k) for k in kws))
    for cat, kws in _KEYWORDS.items()
}


def classify_material_news_type(subject: str) -> str:
    """回傳8大類其中之一，或「其他」。事前綁定規則，不依結果調整。"""
    if not isinstance(subject, str) or not subject:
        return "其他"
    text = subject.replace("\r\n", "").replace("\n", "")
    for cat in PRIORITY_ORDER:
        if _COMPILED[cat].search(text):
            return cat
    return "其他"


